import PDFDocument from "pdfkit";

export function sendPayslipPdf(res, payrollRun, entry) {
  const doc = new PDFDocument({ size: "A4", margin: 54 });
  const employeeCode = String(entry.employeeCode).replace(/[^A-Za-z0-9_-]/g, "_");
  const filename = `payslip-${employeeCode}-${payrollRun.monthKey}.pdf`;
  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${filename}"`);
  res.setHeader("Cache-Control", "private, no-store");
  doc.pipe(res);

  const money = (amount) => new Intl.NumberFormat("en", {
    style: "currency",
    currency: payrollRun.currency,
    minimumFractionDigits: 2
  }).format(amount);

  doc.fillColor("#234d39").fontSize(11).text("PEOPLE OPS", { characterSpacing: 1 });
  doc.moveDown(0.7);
  doc.fillColor("#202820").fontSize(25).text("Payslip");
  doc.moveDown(0.25);
  doc.fillColor("#738078").fontSize(11).text(`Pay period: ${payrollRun.monthKey}`);
  doc.moveDown(1.4);

  const details = [
    ["Employee", entry.employeeName],
    ["Employee ID", entry.employeeCode],
    ["Payroll status", payrollRun.status.toUpperCase()]
  ];
  details.forEach(([label, value]) => {
    doc.fillColor("#738078").fontSize(10).text(label.toUpperCase(), { continued: true, width: 150 });
    doc.fillColor("#202820").fontSize(11).text(value);
    doc.moveDown(0.55);
  });

  doc.moveDown(0.5);
  doc.strokeColor("#dfe7df").moveTo(54, doc.y).lineTo(541, doc.y).stroke();
  doc.moveDown(0.7);
  const rows = [
    ["Monthly salary", money(entry.monthlySalary)],
    ["Calendar days employed", String(entry.proratedDays)],
    ["Prorated gross pay", money(entry.grossPay)],
    [`Attendance deductions (${entry.deductedWorkdays} workdays)`, `-${money(entry.attendanceDeduction)}`],
    ["Taxable pay", money(entry.taxablePay)],
    ["Annualized taxable income", money(entry.annualTaxableIncome)],
    ["Annual tax", money(entry.annualTax)],
    ["Tax withheld this month", `-${money(entry.taxWithheld)}`]
  ];
  rows.forEach(([label, value]) => {
    const y = doc.y;
    doc.fillColor("#55645a").fontSize(10).text(label, 54, y, { width: 330 });
    doc.fillColor("#202820").fontSize(10).text(value, 385, y, { width: 156, align: "right" });
    doc.moveDown(1.15);
  });
  doc.moveDown(0.4);
  doc.strokeColor("#dfe7df").moveTo(54, doc.y).lineTo(541, doc.y).stroke();
  doc.moveDown(0.8);
  const netY = doc.y;
  doc.fillColor("#234d39").fontSize(13).font("Helvetica-Bold").text("NET PAY", 54, netY);
  doc.text(money(entry.netPay), 350, netY, { width: 191, align: "right" });
  doc.font("Helvetica");
  doc.moveDown(3);
  doc.fillColor("#879188").fontSize(9).text(
    "Generated by People Ops. Tax figures use your organization's configured annual tax slabs.",
    54,
    doc.y,
    { width: 480, align: "center" }
  );
  doc.end();
}
